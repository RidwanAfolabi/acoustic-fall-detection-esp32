def evaluate(model, x, y, name: str) -> dict:
    """Accuracy plus per-class precision/recall/F1 for one split."""
    from sklearn.metrics import (
        accuracy_score, confusion_matrix, precision_recall_fscore_support,
        roc_auc_score,
    )

    probs = model.predict(x, verbose=0)
    pred = probs.argmax(axis=1)
    fall = config.LABEL_TO_INDEX["fall"]

    precision, recall, f1, support = precision_recall_fscore_support(
        y, pred, labels=[0, 1], zero_division=0
    )
    try:
        auc = float(roc_auc_score(y, probs[:, fall]))
    except ValueError:
        auc = float("nan")

    result = {
        "split": name,
        "n": int(len(y)),
        "accuracy": float(accuracy_score(y, pred)),
        "auc": auc,
        "confusion_matrix": confusion_matrix(y, pred, labels=[0, 1]).tolist(),
        "fall_precision": float(precision[fall]),
        "fall_recall": float(recall[fall]),
        "fall_f1": float(f1[fall]),
        "per_class": {
            config.INDEX_TO_LABEL[i]: {
                "precision": float(precision[i]), "recall": float(recall[i]),
                "f1": float(f1[i]), "support": int(support[i]),
            }
            for i in (0, 1)
        },
    }
    return result


def evaluate_clips(model, x, y, clip_uids, name: str) -> dict:
    """Clip-level metrics, averaging each clip's window probabilities.

    Window-level labelling is inherently noisy here. A 3 s SAFE clip is sliced
    into five windows and all five inherit the clip's label, but the impact
    itself lasts a fraction of a second and sits mid-clip. Measured mean P(fall)
    by window position confirms it: ~0.49 / 0.85 / 0.92 / 0.92 / 0.60 across
    positions 0-4. The first and last windows are largely background wearing a
    'fall' label, and no model can fit that.

    Averaging over a clip's windows recovers the real signal, and it matches how
    the device should behave: an alerting system can integrate over a second or
    two before raising an alarm rather than firing on a single window.

    Mean is used rather than max deliberately -- max triggers on any single
    confident window and measured far worse (0.68 vs 0.92 accuracy), because it
    turns one spurious window into a false alarm for the whole clip.
    """
    from sklearn.metrics import (
        accuracy_score, confusion_matrix, precision_recall_fscore_support,
        roc_auc_score,
    )

    fall = config.LABEL_TO_INDEX["fall"]
    probs = model.predict(x, verbose=0)[:, fall]
    frame = pd.DataFrame({"uid": clip_uids, "y": y, "p": probs})
    grouped = frame.groupby("uid").agg(y=("y", "first"), p=("p", "mean"))
    pred = (grouped["p"] > 0.5).astype(int).to_numpy()
    truth = grouped["y"].to_numpy()

    precision, recall, f1, _ = precision_recall_fscore_support(
        truth, pred, labels=[0, 1], zero_division=0
    )
    try:
        auc = float(roc_auc_score(truth, grouped["p"].to_numpy()))
    except ValueError:
        auc = float("nan")
    return {
        "split": f"{name}/clip",
        "n": int(len(truth)),
        "accuracy": float(accuracy_score(truth, pred)),
        "auc": auc,
        "confusion_matrix": confusion_matrix(truth, pred, labels=[0, 1]).tolist(),
        "fall_precision": float(precision[fall]),
        "fall_recall": float(recall[fall]),
        "fall_f1": float(f1[fall]),
    }


def log_metrics(result: dict) -> None:
    LOGGER.info(
        "%-6s n=%-6d acc=%.4f  auc=%.4f  fall P=%.4f R=%.4f F1=%.4f",
        result["split"], result["n"], result["accuracy"], result["auc"],
        result["fall_precision"], result["fall_recall"], result["fall_f1"],
    )


def write_curves(history: pd.DataFrame) -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 3, figsize=(15, 4))
    for ax, (key, title) in zip(
        axes, (("loss", "Loss"), ("accuracy", "Accuracy"),
               ("learning_rate", "Learning rate"))
    ):
        if key in history:
            ax.plot(history.index, history[key], label="train", color="#3b7dd8")
        val_key = f"val_{key}"
        if val_key in history:
            ax.plot(history.index, history[val_key], label="val", color="#d1495b")
        ax.set_xlabel("epoch")
        ax.set_title(title)
        if key == "learning_rate":
            ax.set_yscale("log")
        if ax.get_legend_handles_labels()[0]:
            ax.legend()
    fig.tight_layout()
    path = config.FIGURES_DIR / "train_curves.png"
    config.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=140)
    plt.close(fig)
    return path


