# Embedding extraction
# ---------------------------------------------------------------------------


def _chunks_hash(chunks: np.ndarray) -> str:
    """Return a fast SHA-256 fingerprint of the chunks array content.

    Hashes a 1 MB sample (first+middle+last blocks) rather than the full
    444 MB array — fast enough to run every time, sensitive enough to catch
    any Step-2 regeneration that changes the audio content.
    """
    import hashlib
    h = hashlib.sha256()
    n = chunks.shape[0]
    # Sample ~1 MB worth of rows from start, middle, and end
    sample_rows = max(1, 1024 * 1024 // (chunks.shape[1] * 2))  # 2 bytes per int16
    for start in (0, max(0, n // 2 - sample_rows // 2), max(0, n - sample_rows)):
        end = min(start + sample_rows, n)
        h.update(np.asarray(chunks[start:end]).tobytes())
    h.update(str(chunks.shape).encode())
    return h.hexdigest()


def extract_embeddings(
    chunks: np.ndarray, backbone, batch_size: int, cache_path: Path, force: bool
) -> np.ndarray:
    """Run every window through the frozen backbone once, and cache the result.

    A SHA-256 sidecar file (`<cache_path>.sha256`) records the fingerprint of
    the chunks array used to build the cache. If chunks were regenerated by
    Step 2 (different RIRs, negatives, etc.), the fingerprint changes and the
    cache is automatically invalidated — preventing the silent stale-cache bug
    where the head trains on embeddings from a different audio set than Step 5
    evaluates on.
    """
    import tensorflow as tf
    import yamnet_model as ym

    hash_path = cache_path.with_suffix(".sha256")

    if cache_path.exists() and not force:
        cached = np.load(cache_path, mmap_mode="r")
        if cached.shape == (chunks.shape[0], config.EMBEDDING_DIM):
            # Verify the cache was built from the current chunks content
            current_hash = _chunks_hash(chunks)
            stored_hash = hash_path.read_text().strip() if hash_path.exists() else ""
            if current_hash == stored_hash:
                LOGGER.info("Reusing cached embeddings: %s %s", cache_path, cached.shape)
                return np.asarray(cached)
            LOGGER.info(
                "Chunks content has changed since cache was built "
                "(Step 2 was re-run with different settings). Recomputing embeddings."
            )
        else:
            LOGGER.info("Cache shape %s does not match corpus; recomputing.", cached.shape)

    inputs = tf.keras.Input(shape=(config.WINDOW_SAMPLES,), dtype=tf.float32)
    extractor = tf.keras.Model(
        inputs, backbone(ym.LogMelLayer(name="log_mel")(inputs)), name="extractor"
    )

    total = chunks.shape[0]
    out = np.zeros((total, config.EMBEDDING_DIM), dtype=np.float32)
    from tqdm import tqdm

    for start in tqdm(
        range(0, total, batch_size), desc="Embedding", unit="batch", ncols=78,
        disable=not sys.stderr.isatty(),
    ):
        stop = min(start + batch_size, total)
        batch = np.asarray(chunks[start:stop], dtype=np.float32) / 32768.0
        out[start:stop] = extractor(batch, training=False).numpy()

    cache_path.parent.mkdir(parents=True, exist_ok=True)
    np.save(cache_path, out)
    # Write hash sidecar so future runs can detect if chunks were regenerated
    hash_path.write_text(_chunks_hash(chunks))
    LOGGER.info("Cached embeddings -> %s (%.1f MB)",
                cache_path, cache_path.stat().st_size / 1e6)
    return out


