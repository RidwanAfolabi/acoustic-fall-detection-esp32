"""
STEP 4 - YAMNet transfer learning.

The backbone stays frozen. Only a small head is trained:

    1024-d embedding -> Dense(128, relu) -> Dropout(0.4) -> Dense(2, softmax)

That is ~131 k trainable parameters against 3.2 M frozen ones, which is the
whole point of transfer learning here: 665 training clips could never fit an
audio CNN from scratch, but they are ample for re-mapping a feature space
AudioSet already learned from ~2 M clips.

Because the backbone is frozen, it is run exactly **once**. Every window's
embedding is computed up front and cached, and training then iterates over
1024-float vectors instead of re-running a 3.2 M parameter CNN each epoch. This
turns epochs from minutes into fractions of a second.

Two correctness guards run before any training happens:

  * the rebuilt front-end + backbone is verified numerically against TF-Hub, so
    the head cannot be trained on a feature space the device will not reproduce;
  * embeddings are extracted through the *rebuilt* model, not TF-Hub, so the
    features used for training are byte-for-byte the ones Step 5 exports.

Outputs
    models/yamnet_fall_detector.keras   float32 composite (patch -> 2 classes)
    models/yamnet_fall_detector.h5      same, legacy format
    models/fall_head.keras              head alone
    data/processed/embeddings.npy       cached 1024-d embeddings
    outputs/train_metrics.json, outputs/training_history.csv
    outputs/figures/train_curves.png

Usage
    python src/4_train.py
    python src/4_train.py --epochs 300 --batch-size 128
    python src/4_train.py --skip-verify        # only if already verified
"""

