def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Train the YAMNet fall-detection head.")
    p.add_argument("--processed-dir", type=Path, default=config.PROCESSED_DIR)
    p.add_argument("--splits-dir", type=Path, default=config.SPLITS_DIR)
    p.add_argument("--models-dir", type=Path, default=config.MODELS_DIR)
    p.add_argument("--epochs", type=int, default=200)
    p.add_argument("--batch-size", type=int, default=64)
    p.add_argument("--extract-batch", type=int, default=128)
    p.add_argument("--learning-rate", type=float, default=1e-3)
    p.add_argument("--hidden-units", type=int, default=128)
    p.add_argument("--dropout", type=float, default=0.4)
    p.add_argument("--patience", type=int, default=15)
    p.add_argument("--lr-patience", type=int, default=6)
    p.add_argument("--seed", type=int, default=config.RANDOM_SEED)
    p.add_argument("--force-extract", action="store_true")
    p.add_argument("--skip-verify", action="store_true")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    config.ensure_dirs()
    setup_logging(config.LOGS_DIR / "train.log")

    import tensorflow as tf
    import yamnet_model as ym

    tf.keras.utils.set_random_seed(args.seed)

    section("YAMNET TRANSFER LEARNING  -  Step 4")
    LOGGER.info("TensorFlow ......... %s", tf.__version__)

    chunks_path = args.processed_dir / "chunks_int16.npy"
    if not chunks_path.exists():
        LOGGER.info("Missing %s - run Step 2 first.", chunks_path)
        return 2
    indices = {}
    for name in ("train", "val", "test"):
        path = args.splits_dir / f"{name}_indices.npy"
        if not path.exists():
            LOGGER.info("Missing %s - run Step 3 first.", path)
            return 2
        indices[name] = np.load(path)

    chunks = np.load(chunks_path, mmap_mode="r")
    manifest = pd.read_csv(
        args.splits_dir / "split_manifest.csv",
        dtype={"clip_uid": str, "fold_id": str},
    )
    labels = manifest.set_index("chunk_index")["label_index"].to_numpy()
    LOGGER.info("Windows ............ %d", chunks.shape[0])
    LOGGER.info("train/val/test ..... %d / %d / %d",
                *(len(indices[s]) for s in ("train", "val", "test")))

    # --- backbone ---
    section("FROZEN BACKBONE")
    weights = ym.download_weights(args.models_dir)
    backbone = ym.build_backbone(include_logits=False)
    applied = ym.load_yamnet_weights(backbone, weights)
    backbone.trainable = False
    LOGGER.info("weights ............ %s (%.1f MB)", weights.name,
                weights.stat().st_size / 1e6)
    LOGGER.info("layers populated ... %d", applied)
    LOGGER.info("parameters ......... %d frozen", backbone.count_params())

    checks: dict | None = None
    if not args.skip_verify:
        section("REBUILD VERIFICATION vs TF-HUB")
        LOGGER.info(
            "The head must be trained on the same feature space the device\n"
            "will compute. Comparing the rebuilt front-end and backbone against\n"
            "TF-Hub YAMNet on real corpus audio.\n"
        )
        sample = np.stack([
            np.asarray(chunks[i], dtype=np.float32) / 32768.0
            for i in np.linspace(0, chunks.shape[0] - 1, 6, dtype=int)
        ])
        checks = ym.verify_against_hub(sample, backbone)
        for key, value in checks.items():
            LOGGER.info("  %-26s %.4e", key, value)
        if checks["relative_embedding_diff"] > 1e-3:
            LOGGER.info(
                "\nFAIL: rebuilt backbone diverges from TF-Hub. Refusing to train."
            )
            return 1
        LOGGER.info("\nPASS - rebuild matches TF-Hub to floating-point noise.")

    # --- embeddings ---
    section("EMBEDDING EXTRACTION")
    embeddings = extract_embeddings(
        chunks, backbone, args.extract_batch,
        args.processed_dir / "embeddings.npy", args.force_extract,
    )
    LOGGER.info("embeddings ......... %s", embeddings.shape)

    x = {s: embeddings[indices[s]] for s in indices}
    y = {s: labels[indices[s]] for s in indices}
    for name in ("train", "val", "test"):
        counts = np.bincount(y[name], minlength=config.NUM_CLASSES)
        LOGGER.info("  %-5s %5d windows  non_fall=%d fall=%d",
                    name, len(y[name]), counts[0], counts[1])

    # --- head ---
    section("CLASSIFICATION HEAD")
    head = ym.build_head(hidden_units=args.hidden_units, dropout=args.dropout)
    head.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=args.learning_rate),
        loss="sparse_categorical_crossentropy",
        # AUC is deliberately absent: Keras' AUC metric expects a single
        # binary output, not a 2-class softmax with sparse labels. It is
        # computed from probabilities by sklearn in evaluate() instead.
        metrics=["accuracy"],
    )
    head.summary(print_fn=LOGGER.info)

    summary_path = args.splits_dir / "splits_summary.json"
    weights_map = None
    if summary_path.exists():
        raw = json.loads(summary_path.read_text()).get("class_weights", {})
        weights_map = {int(k): float(v) for k, v in raw.items()}
        LOGGER.info("class weights ...... %s", weights_map)

    callbacks = [
        tf.keras.callbacks.EarlyStopping(
            monitor="val_loss", patience=args.patience,
            restore_best_weights=True, verbose=1,
        ),
        tf.keras.callbacks.ReduceLROnPlateau(
            monitor="val_loss", factor=0.5, patience=args.lr_patience,
            min_lr=1e-6, verbose=1,
        ),
    ]

    section("TRAINING")
    history = head.fit(
        x["train"], y["train"],
        validation_data=(x["val"], y["val"]),
        epochs=args.epochs, batch_size=args.batch_size,
        class_weight=weights_map, callbacks=callbacks, verbose=2,
    )
    frame = pd.DataFrame(history.history)
    frame.index.name = "epoch"
    frame.to_csv(config.OUTPUTS_DIR / "training_history.csv")
    LOGGER.info("\nEpochs run ......... %d", len(frame))
    LOGGER.info("Best val_loss ...... %.4f (epoch %d)",
                frame["val_loss"].min(), int(frame["val_loss"].idxmin()))

    # --- metrics ---
    section("METRICS")
    results = [evaluate(head, x[s], y[s], s) for s in ("train", "val", "test")]
    for result in results:
        log_metrics(result)

    LOGGER.info("\nClip-level (mean over each clip's windows):")
    uids = manifest.set_index("chunk_index")["clip_uid"]
    for name in ("val", "test"):
        clip_result = evaluate_clips(
            head, x[name], y[name], uids.loc[indices[name]].to_numpy(), name
        )
        log_metrics(clip_result)
        results.append(clip_result)
    LOGGER.info(
        "\nTest numbers are reported here for visibility only; Step 5 does the\n"
        "full confusion-matrix and threshold analysis on the quantised model."
    )

    # --- save ---
    section("SAVING MODELS")
    args.models_dir.mkdir(parents=True, exist_ok=True)
    composite = ym.build_composite(backbone, head)
    composite.compile()

    head_path = args.models_dir / "fall_head.keras"
    head.save(head_path)
    keras_path = args.models_dir / "yamnet_fall_detector.keras"
    composite.save(keras_path)
    LOGGER.info("head ............... %s", head_path)
    LOGGER.info("composite (.keras) . %s (%.1f MB)", keras_path,
                keras_path.stat().st_size / 1e6)

    h5_path = args.models_dir / "yamnet_fall_detector.h5"
    try:
        composite.save(h5_path)
        LOGGER.info("composite (.h5) .... %s (%.1f MB)", h5_path,
                    h5_path.stat().st_size / 1e6)
    except Exception as exc:  # noqa: BLE001 - legacy format is best-effort
        LOGGER.info("composite (.h5) .... not written (%s: %s)",
                    type(exc).__name__, exc)

    LOGGER.info("\nComposite input  ... %s", composite.input_shape)
    LOGGER.info("Composite output ... %s", composite.output_shape)
    LOGGER.info("Total parameters ... %d (%d trainable)",
                composite.count_params(),
                sum(int(np.prod(w.shape)) for w in composite.trainable_weights))

    metrics = {
        "tensorflow": tf.__version__,
        "epochs_run": int(len(frame)),
        "best_val_loss": float(frame["val_loss"].min()),
        "best_epoch": int(frame["val_loss"].idxmin()),
        "hidden_units": args.hidden_units,
        "dropout": args.dropout,
        "learning_rate": args.learning_rate,
        "batch_size": args.batch_size,
        "seed": args.seed,
        "verification": checks,
        "results": {r["split"]: r for r in results},
    }
    (config.OUTPUTS_DIR / "train_metrics.json").write_text(
        json.dumps(metrics, indent=2), encoding="utf-8"
    )

    curves = write_curves(frame)
    section("ARTEFACTS")
    LOGGER.info("metrics .... %s", config.OUTPUTS_DIR / "train_metrics.json")
    LOGGER.info("history .... %s", config.OUTPUTS_DIR / "training_history.csv")
    LOGGER.info("figure ..... %s", curves)

    section("RESULT")
    val = next(r for r in results if r["split"] == "val")
    LOGGER.info("Validation accuracy %.4f, fall F1 %.4f. Ready for Step 5.",
                val["accuracy"], val["fall_f1"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
