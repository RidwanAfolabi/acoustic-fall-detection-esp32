def export_c_array(
    tflite_bytes: bytes,
    header_path: Path,
    source_path: Path,
    input_scale: float,
    input_zero_point: int,
    output_scale: float,
    output_zero_point: int,
) -> None:
    """Generate C header and source files containing the aligned TFLite model data."""
    header_path.parent.mkdir(parents=True, exist_ok=True)
    source_path.parent.mkdir(parents=True, exist_ok=True)

    header_content = f"""// Auto-generated by src/5_export_tflite.py
// Acoustic Emergency Alerting System - ESP32-S3-BOX-3 Model Data
#ifndef YAMNET_MODEL_DATA_H_
#define YAMNET_MODEL_DATA_H_

#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

// Model input/output dimensions
#define YAMNET_INPUT_FRAMES       {config.PATCH_FRAMES}
#define YAMNET_INPUT_BANDS        {config.MEL_BANDS}
#define YAMNET_INPUT_CHANNELS     1
#define YAMNET_NUM_CLASSES        {config.NUM_CLASSES}

// Input quantization parameters (int8):
//   quantized_val = round(real_val / YAMNET_INPUT_SCALE) + YAMNET_INPUT_ZERO_POINT
//   real_val      = (quantized_val - YAMNET_INPUT_ZERO_POINT) * YAMNET_INPUT_SCALE
#define YAMNET_INPUT_SCALE        {input_scale:.8e}f
#define YAMNET_INPUT_ZERO_POINT   {input_zero_point}

// Output quantization parameters (int8):
//   probability   = (quantized_val - YAMNET_OUTPUT_ZERO_POINT) * YAMNET_OUTPUT_SCALE
#define YAMNET_OUTPUT_SCALE       {output_scale:.8e}f
#define YAMNET_OUTPUT_ZERO_POINT  {output_zero_point}

// Model FlatBuffer binary (16-byte aligned for TFLite Micro in PSRAM/Flash)
extern const unsigned char g_yamnet_model_data[];
extern const unsigned int g_yamnet_model_data_len;

#ifdef __cplusplus
}}
#endif

#endif  // YAMNET_MODEL_DATA_H_
"""

    with open(header_path, "w", encoding="utf-8") as f:
        f.write(header_content)

    # Format bytes in hex columns
    hex_lines = []
    line_bytes = []
    for i, b in enumerate(tflite_bytes):
        line_bytes.append(f"0x{b:02x}")
        if len(line_bytes) == 12 or i == len(tflite_bytes) - 1:
            hex_lines.append("    " + ", ".join(line_bytes) + ",")
            line_bytes = []

    body = "\n".join(hex_lines)
    source_content = f"""// Auto-generated by src/5_export_tflite.py
#include "{header_path.name}"

#if defined(__GNUC__) || defined(__clang__)
#define YAMNET_ALIGN __attribute__((aligned(16)))
#else
#define YAMNET_ALIGN alignas(16)
#endif

YAMNET_ALIGN const unsigned char g_yamnet_model_data[] = {{
{body}
}};

const unsigned int g_yamnet_model_data_len = {len(tflite_bytes)};
"""

    with open(source_path, "w", encoding="utf-8") as f:
        f.write(source_content)


