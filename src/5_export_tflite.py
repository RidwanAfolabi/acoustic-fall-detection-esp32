"""
STEP 5 - TFLite export, INT8 post-training quantization, and C header generation.

This step bridges the desktop ML pipeline to the ESP32-S3 firmware:

1. Wraps the trained composite model (96, 64, 1) log-mel patch -> 2 classes with a
   static batch size of 1, required by TensorFlow Lite Micro on microcontrollers.
2. Converts the baseline Float32 model to TFLite format.
3. Performs full INT8 Post-Training Quantization (PTQ) using representative
   calibration log-mel patches generated from the training split.
4. Validates numerical parity between Float32 and INT8 on the held-out test and
   validation splits, reporting window-level and clip-level metrics (accuracy,
   recall, precision, F1, AUC, and confusion matrices).
5. Sweeps decision thresholds to evaluate the precision/recall trade-off.
6. Exports the quantized model as a 16-byte aligned C byte array header and
   source file (`yamnet_model_data.h` and `yamnet_model_data.cc`) with exact
   quantization scale and zero-point parameters for direct compilation into
   the ESP32-S3 firmware.

Outputs
    models/yamnet_fall_detector_float32.tflite
    models/yamnet_fall_detector_int8.tflite
    models/yamnet_model_data.h
    models/yamnet_model_data.cc
    outputs/tflite_metrics.json
    outputs/figures/tflite_eval.png
    outputs/logs/export_tflite.log

Usage
    python src/5_export_tflite.py
    python src/5_export_tflite.py --num-calibration 400
    python src/5_export_tflite.py --skip-eval
"""

