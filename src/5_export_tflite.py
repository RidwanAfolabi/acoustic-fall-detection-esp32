class TFLiteWrapper:
    """Convenience wrapper around tf.lite.Interpreter for batch inference."""

    def __init__(self, model_bytes: bytes):
        import tensorflow as tf

        self.interpreter = tf.lite.Interpreter(model_content=model_bytes)
        self.interpreter.allocate_tensors()
        self.input_details = self.interpreter.get_input_details()[0]
        self.output_details = self.interpreter.get_output_details()[0]
        self.is_int8 = self.input_details["dtype"] == np.int8

        self.input_scale, self.input_zero_point = self.input_details["quantization"]
        self.output_scale, self.output_zero_point = self.output_details["quantization"]

    def predict_one(self, patch_f32: np.ndarray) -> np.ndarray:
        """Run single (1, 96, 64, 1) patch. Returns (2,) probabilities."""
        if self.is_int8:
            q_input = np.clip(
                np.round(patch_f32 / self.input_scale + self.input_zero_point),
                -128,
                127,
            ).astype(np.int8)
            self.interpreter.set_tensor(self.input_details["index"], q_input)
            self.interpreter.invoke()
            q_output = self.interpreter.get_tensor(self.output_details["index"])[0]
            probs = (q_output.astype(np.float32) - self.output_zero_point) * self.output_scale
            # Renormalize to ensure clean sum=1
            s = probs.sum()
            if s > 0:
                probs = probs / s
            return probs
        else:
            self.interpreter.set_tensor(
                self.input_details["index"], patch_f32.astype(np.float32)
            )
            self.interpreter.invoke()
            return self.interpreter.get_tensor(self.output_details["index"])[0]

    def predict_batch(self, patches: np.ndarray) -> np.ndarray:
        """Run array of (N, 96, 64, 1) patches. Returns (N, 2) probabilities."""
        n = patches.shape[0]
        probs = np.zeros((n, config.NUM_CLASSES), dtype=np.float32)
        for i in range(n):
            probs[i] = self.predict_one(patches[i : i + 1])
        return probs


