def compute_metrics(y_true: np.ndarray, probs: np.ndarray, threshold: float = 0.5) -> dict:
    fall_idx = config.LABEL_TO_INDEX["fall"]
    fall_probs = probs[:, fall_idx]
    y_pred = (fall_probs >= threshold).astype(int)

    precision, recall, f1, support = precision_recall_fscore_support(
        y_true, y_pred, labels=[0, 1], zero_division=0
    )
    try:
        auc = float(roc_auc_score(y_true, fall_probs))
    except ValueError:
        auc = float("nan")

    return {
        "n": int(len(y_true)),
        "threshold": float(threshold),
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "auc": auc,
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=[0, 1]).tolist(),
        "fall_precision": float(precision[fall_idx]),
        "fall_recall": float(recall[fall_idx]),
        "fall_f1": float(f1[fall_idx]),
        "non_fall_precision": float(precision[0]),
        "non_fall_recall": float(recall[0]),
        "non_fall_f1": float(f1[0]),
    }


def compute_clip_metrics(
    uids: np.ndarray, y_true: np.ndarray, probs: np.ndarray, threshold: float = 0.5
) -> dict:
    fall_idx = config.LABEL_TO_INDEX["fall"]
    fall_probs = probs[:, fall_idx]
    df = pd.DataFrame({"uid": uids, "y": y_true, "p": fall_probs})
    grouped = df.groupby("uid").agg(y=("y", "first"), p=("p", "mean"))

    truth = grouped["y"].to_numpy()
    mean_probs = grouped["p"].to_numpy()
    pred = (mean_probs >= threshold).astype(int)

    precision, recall, f1, _ = precision_recall_fscore_support(
        truth, pred, labels=[0, 1], zero_division=0
    )
    try:
        auc = float(roc_auc_score(truth, mean_probs))
    except ValueError:
        auc = float("nan")

    return {
        "n_clips": int(len(truth)),
        "threshold": float(threshold),
        "accuracy": float(accuracy_score(truth, pred)),
        "auc": auc,
        "confusion_matrix": confusion_matrix(truth, pred, labels=[0, 1]).tolist(),
        "fall_precision": float(precision[fall_idx]),
        "fall_recall": float(recall[fall_idx]),
        "fall_f1": float(f1[fall_idx]),
        "non_fall_precision": float(precision[0]),
        "non_fall_recall": float(recall[0]),
        "non_fall_f1": float(f1[0]),
        "mean_probs": mean_probs,
        "truth": truth,
    }


def sweep_thresholds(
    truth: np.ndarray, probs: np.ndarray
) -> list[dict[str, float]]:
    records = []
    for t in np.linspace(0.05, 0.95, 19):
        pred = (probs >= t).astype(int)
        precision, recall, f1, _ = precision_recall_fscore_support(
            truth, pred, labels=[0, 1], zero_division=0
        )
        records.append(
            {
                "threshold": float(t),
                "accuracy": float(accuracy_score(truth, pred)),
                "precision": float(precision[1]),
                "recall": float(recall[1]),
                "f1": float(f1[1]),
            }
        )
    return records


