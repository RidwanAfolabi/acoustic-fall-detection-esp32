def run(args: argparse.Namespace) -> int:
    import tensorflow as tf

    setup_logging(args.logs_dir / "export_tflite.log")
    section("STEP 5 - TFLITE INT8 QUANTIZATION & C EXPORT")
    LOGGER.info("TensorFlow version ..... %s", tf.__version__)
    LOGGER.info("Model path ............. %s", args.model_path)
    LOGGER.info("Output dir ............. %s", args.models_dir)

    if not args.model_path.exists():
        LOGGER.error("Model %s does not exist. Run Step 4 first!", args.model_path)
        return 2

    # 1. Load trained Keras composite model
    section("1. LOADING KERAS MODEL & CREATING STATIC BATCH GRAPH")
    keras_model = tf.keras.models.load_model(args.model_path)
    LOGGER.info("Loaded Keras model: %s (%d params)", keras_model.name, keras_model.count_params())

    # Build static-shape model for TFLite Micro: batch=1, (1, 96, 64, 1)
    static_in = tf.keras.Input(
        batch_shape=(1, config.PATCH_FRAMES, config.MEL_BANDS, 1),
        dtype=tf.float32,
        name="log_mel_patch",
    )
    static_out = keras_model(static_in)
    static_model = tf.keras.Model(static_in, static_out, name="yamnet_static_detector")

    # 2. Convert to Float32 TFLite
    section("2. CONVERTING FLOAT32 TFLITE BASELINE")
    f32_converter = tf.lite.TFLiteConverter.from_keras_model(static_model)
    f32_tflite_bytes = f32_converter.convert()
    f32_tflite_path = args.models_dir / "yamnet_fall_detector_float32.tflite"
    with open(f32_tflite_path, "wb") as f:
        f.write(f32_tflite_bytes)
    LOGGER.info("Float32 TFLite saved ... %s (%.2f MB)", f32_tflite_path.name, len(f32_tflite_bytes) / 1e6)

    # 3. Prepare Calibration Data for INT8 PTQ
    section("3. INT8 POST-TRAINING QUANTIZATION (PTQ)")
    chunks_path = args.processed_dir / "chunks_int16.npy"
    train_idx_path = args.splits_dir / "train_indices.npy"
    if not chunks_path.exists() or not train_idx_path.exists():
        LOGGER.error("Missing data artifacts. Run Steps 2 and 3 first!")
        return 2

    chunks = np.load(chunks_path, mmap_mode="r")
    train_indices = np.load(train_idx_path)

    rng = np.random.default_rng(args.seed)
    n_calib = min(args.num_calibration, len(train_indices))
    sample_indices = rng.choice(train_indices, size=n_calib, replace=False)
    LOGGER.info("Sampling %d training windows for calibration...", n_calib)

    # Pre-extract calibration log-mel patches
    calib_waveforms = (chunks[sample_indices].astype(np.float32) / 32768.0)
    calib_patches = ym.build_log_mel(tf.constant(calib_waveforms)).numpy()
    LOGGER.info("Calibration patches shape: %s", calib_patches.shape)

    def representative_dataset_gen():
        for i in range(n_calib):
            yield [calib_patches[i : i + 1].astype(np.float32)]

    # INT8 Quantization configuration
    int8_converter = tf.lite.TFLiteConverter.from_keras_model(static_model)
    int8_converter.optimizations = [tf.lite.Optimize.DEFAULT]
    int8_converter.representative_dataset = representative_dataset_gen
    int8_converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    int8_converter.inference_input_type = tf.int8
    int8_converter.inference_output_type = tf.int8

    LOGGER.info("Running INT8 quantization converter...")
    int8_tflite_bytes = int8_converter.convert()
    int8_tflite_path = args.models_dir / "yamnet_fall_detector_int8.tflite"
    with open(int8_tflite_path, "wb") as f:
        f.write(int8_tflite_bytes)

    ratio = len(f32_tflite_bytes) / len(int8_tflite_bytes)
    LOGGER.info("INT8 TFLite saved ...... %s (%.2f MB)", int8_tflite_path.name, len(int8_tflite_bytes) / 1e6)
    LOGGER.info("Compression ratio ..... %.2fx reduction vs Float32", ratio)

    # 4. Inspect Quantization Parameters & Export C Files
    section("4. QUANTIZATION PARAMETERS & C EXPORT")
    int8_wrapper = TFLiteWrapper(int8_tflite_bytes)
    LOGGER.info("Input Tensor:")
    LOGGER.info("  Shape ............... %s", int8_wrapper.input_details["shape"].tolist())
    LOGGER.info("  Type ................ %s", int8_wrapper.input_details["dtype"].__name__)
    LOGGER.info("  Scale ............... %.8e", int8_wrapper.input_scale)
    LOGGER.info("  Zero point .......... %d", int8_wrapper.input_zero_point)
    LOGGER.info("Output Tensor:")
    LOGGER.info("  Shape ............... %s", int8_wrapper.output_details["shape"].tolist())
    LOGGER.info("  Type ................ %s", int8_wrapper.output_details["dtype"].__name__)
    LOGGER.info("  Scale ............... %.8e", int8_wrapper.output_scale)
    LOGGER.info("  Zero point .......... %d", int8_wrapper.output_zero_point)

    header_path = args.models_dir / "yamnet_model_data.h"
    source_path = args.models_dir / "yamnet_model_data.cc"
    export_c_array(
        int8_tflite_bytes,
        header_path,
        source_path,
        int8_wrapper.input_scale,
        int8_wrapper.input_zero_point,
        int8_wrapper.output_scale,
        int8_wrapper.output_zero_point,
    )
    LOGGER.info("C header exported ..... %s", header_path)
    LOGGER.info("C source exported ..... %s (%.2f MB)", source_path, source_path.stat().st_size / 1e6)

    if args.skip_eval:
        LOGGER.info("\nEvaluation skipped via --skip-eval. Step 5 complete.")
        return 0

    # 5. Parity & Validation on Test & Validation Sets
    section("5. NUMERICAL PARITY & EVALUATION")
    f32_wrapper = TFLiteWrapper(f32_tflite_bytes)

    manifest = pd.read_csv(
        args.splits_dir / "split_manifest.csv",
        dtype={"clip_uid": str, "fold_id": str},
    )
    manifest_by_chunk = manifest.set_index("chunk_index")

    test_indices = np.load(args.splits_dir / "test_indices.npy")
    val_indices = np.load(args.splits_dir / "val_indices.npy")

    eval_splits = {"test": test_indices, "val": val_indices}
    all_results = {
        "model_sizes": {
            "keras_h5_mb": (args.models_dir / "yamnet_fall_detector.h5").stat().st_size / 1e6
            if (args.models_dir / "yamnet_fall_detector.h5").exists()
            else None,
            "float32_tflite_mb": len(f32_tflite_bytes) / 1e6,
            "int8_tflite_mb": len(int8_tflite_bytes) / 1e6,
            "compression_ratio": ratio,
        },
        "quantization": {
            "input_scale": float(int8_wrapper.input_scale),
            "input_zero_point": int(int8_wrapper.input_zero_point),
            "output_scale": float(int8_wrapper.output_scale),
            "output_zero_point": int(int8_wrapper.output_zero_point),
        },
        "splits": {},
    }

    test_pred_cache = {}

    for s_name, indices in eval_splits.items():
        LOGGER.info("\nEvaluating split: %s (%d windows)...", s_name, len(indices))
        split_waveforms = chunks[indices].astype(np.float32) / 32768.0
        split_patches = ym.build_log_mel(tf.constant(split_waveforms)).numpy()

        y_true = manifest_by_chunk.loc[indices, "label_index"].to_numpy()
        uids = manifest_by_chunk.loc[indices, "clip_uid"].to_numpy()

        # Run Keras, Float32 TFLite, INT8 TFLite
        t0 = time.perf_counter()
        p_keras = keras_model.predict(split_patches, batch_size=args.batch_size, verbose=0)
        t_keras = time.perf_counter() - t0

        t0 = time.perf_counter()
        p_f32 = f32_wrapper.predict_batch(split_patches)
        t_f32 = time.perf_counter() - t0

        t0 = time.perf_counter()
        p_int8 = int8_wrapper.predict_batch(split_patches)
        t_int8 = time.perf_counter() - t0

        # Parity analysis
        diff_keras_f32 = np.abs(p_keras - p_f32)[:, 1]
        diff_f32_int8 = np.abs(p_f32 - p_int8)[:, 1]

        LOGGER.info("  Parity: Max diff |Keras - TFLite_F32| = %.2e (mean %.2e)",
                    diff_keras_f32.max(), diff_keras_f32.mean())
        LOGGER.info("  Parity: Max diff |TFLite_F32 - INT8|  = %.2e (mean %.2e)",
                    diff_f32_int8.max(), diff_f32_int8.mean())

        # Window metrics
        w_f32 = compute_metrics(y_true, p_f32)
        w_int8 = compute_metrics(y_true, p_int8)

        # Clip metrics
        c_f32 = compute_clip_metrics(uids, y_true, p_f32)
        c_int8 = compute_clip_metrics(uids, y_true, p_int8)

        if s_name == "test":
            test_pred_cache = {
                "y_true": y_true,
                "uids": uids,
                "p_f32": p_f32,
                "p_int8": p_int8,
                "c_int8": c_int8,
                "diff_f32_int8": diff_f32_int8,
            }

        LOGGER.info("  Window [%s]: F32 Acc=%.4f, INT8 Acc=%.4f (Delta = %+.4f)",
                    s_name, w_f32["accuracy"], w_int8["accuracy"], w_int8["accuracy"] - w_f32["accuracy"])
        LOGGER.info("  Window [%s]: F32 Fall F1=%.4f, INT8 Fall F1=%.4f",
                    s_name, w_f32["fall_f1"], w_int8["fall_f1"])
        LOGGER.info("  Clip   [%s]: F32 Acc=%.4f, INT8 Acc=%.4f (Recall=%.4f, Prec=%.4f)",
                    s_name, c_f32["accuracy"], c_int8["accuracy"], c_int8["fall_recall"], c_int8["fall_precision"])

        all_results["splits"][s_name] = {
            "parity": {
                "max_diff_f32_int8": float(diff_f32_int8.max()),
                "mean_diff_f32_int8": float(diff_f32_int8.mean()),
            },
            "window_f32": w_f32,
            "window_int8": w_int8,
            "clip_f32": {k: v for k, v in c_f32.items() if k not in ("mean_probs", "truth")},
            "clip_int8": {k: v for k, v in c_int8.items() if k not in ("mean_probs", "truth")},
        }

    # 6. Threshold Sweep on Held-out Test Set
    section("6. DECISION THRESHOLD ANALYSIS (TEST SET)")
    clip_truth = test_pred_cache["c_int8"]["truth"]
    clip_probs = test_pred_cache["c_int8"]["mean_probs"]
    sweep_results = sweep_thresholds(clip_truth, clip_probs)
    all_results["threshold_sweep"] = sweep_results

    LOGGER.info("Threshold Sweep on Held-out Test Clips (INT8):")
    LOGGER.info("  Thresh | Accuracy | Precision | Recall |   F1  ")
    LOGGER.info("  -------+----------+-----------+--------+-------")
    for rec in sweep_results:
        LOGGER.info("   %0.2f  |  %0.4f  |   %0.4f  | %0.4f | %0.4f",
                    rec["threshold"], rec["accuracy"], rec["precision"], rec["recall"], rec["f1"])

    # 7. Generate Evaluation Figures
    section("7. GENERATING EVALUATION PLOT")
    fig, axes = plt.subplots(2, 2, figsize=(13, 10))

    # Subplot 1: ROC Curves (Keras Float32 vs INT8)
    fpr_f32, tpr_f32, _ = roc_curve(test_pred_cache["y_true"], test_pred_cache["p_f32"][:, 1])
    fpr_int8, tpr_int8, _ = roc_curve(test_pred_cache["y_true"], test_pred_cache["p_int8"][:, 1])
    axes[0, 0].plot(fpr_f32, tpr_f32, label=f"Float32 TFLite (AUC={all_results['splits']['test']['window_f32']['auc']:.3f})", lw=2)
    axes[0, 0].plot(fpr_int8, tpr_int8, label=f"INT8 TFLite (AUC={all_results['splits']['test']['window_int8']['auc']:.3f})", lw=2, linestyle="--")
    axes[0, 0].plot([0, 1], [0, 1], "k--", alpha=0.5)
    axes[0, 0].set_title("Window-Level ROC Curves (Test Set)")
    axes[0, 0].set_xlabel("False Positive Rate")
    axes[0, 0].set_ylabel("True Positive Rate")
    axes[0, 0].legend(loc="lower right")
    axes[0, 0].grid(True, alpha=0.3)

    # Subplot 2: Probability Differences Histogram (|Float32 - INT8|)
    axes[0, 1].hist(test_pred_cache["diff_f32_int8"], bins=30, color="skyblue", edgecolor="black", alpha=0.8)
